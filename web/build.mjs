// Bundles the web app into a single self-contained index.html
// (scripts, styles and the Literata typeface inlined) for the Android assets.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const watch = process.argv.includes('--dev');

// 1. Fonts, embedded as data URIs so the app works offline:
//    Literata for prose (400/400i/600/700/700i), Balsamiq Sans for comic lettering
//    (400/700) and Bangers + Russo One for sound effects. Latin and Cyrillic (incl. Kazakh).
function fontFaces(pkg, faces, subsets) {
  const dir = join(here, 'node_modules/@fontsource', pkg);
  let css = '';
  for (const f of faces) {
    const src = readFileSync(join(dir, f), 'utf8');
    for (const block of src.split('/*').slice(1)) {
      const name = block.slice(0, block.indexOf('*/')).trim(); // e.g. literata-cyrillic-400-normal
      const subset = name.replace(new RegExp(`^${pkg}-`), '').replace(/-\d+-(normal|italic)$/, '');
      if (!subsets.includes(subset)) continue;
      const face = block.slice(block.indexOf('@font-face'));
      const woff2 = face.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      const data = readFileSync(join(dir, 'files', woff2)).toString('base64');
      css += face
        .replace(/src:[^;]+;/, `src: url(data:font/woff2;base64,${data}) format('woff2');`)
        .replace(/font-display: swap;/, 'font-display: block;')
        .replace(/\s+/g, ' ') + '\n';
    }
  }
  return css;
}
const ALL = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];
const fontCss = fontFaces('literata', ['400.css', '400-italic.css', '600.css', '700.css', '700-italic.css'], ALL);
const comicCss =
  fontFaces('balsamiq-sans', ['400.css', '700.css'], ALL) +
  fontFaces('bangers', ['400.css'], ALL) +
  fontFaces('russo-one', ['400.css'], ALL);
mkdirSync(join(here, 'src/gen'), { recursive: true });
writeFileSync(join(here, 'src/gen/fonts.js'),
  `// Generated by build.mjs — do not edit.\nexport const FONT_CSS = ${JSON.stringify(fontCss)};\nexport const COMIC_FONT_CSS = ${JSON.stringify(comicCss)};\n`);

// 2. Bundle JS + CSS.
const result = await build({
  entryPoints: [join(here, 'src/main.js')],
  bundle: true,
  minify: !watch,
  format: 'iife',
  target: ['chrome90'],
  write: false,
  outdir: join(here, 'out'),
  legalComments: 'none',
  logLevel: 'warning',
});
const js = result.outputFiles.find((f) => f.path.endsWith('.js')).text;
const css = result.outputFiles.find((f) => f.path.endsWith('.css')).text;

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, interactive-widget=resizes-content">
<meta name="theme-color" content="#F2F3EE">
<meta name="color-scheme" content="light dark">
<title>Bookative</title>
<style>${css}</style>
</head>
<body>
<div id="app"></div>
<script>${js.replace(/<\/script/gi, '<\\/script')}</script>
</body>
</html>
`;

const outFiles = [join(here, '../android/assets/index.html'), join(here, 'dist/index.html')];
for (const f of outFiles) {
  mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, html);
}
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB (fonts ${((fontCss.length + comicCss.length) / 1024).toFixed(0)} KB)`);
